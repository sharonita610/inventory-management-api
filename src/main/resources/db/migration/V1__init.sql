CREATE TABLE product (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(100) NOT NULL,
    quantity   BIGINT       NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_product_name UNIQUE (name),
    CONSTRAINT ck_product_quantity_non_negative CHECK (quantity >= 0)
);

CREATE TABLE stock_history (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id     BIGINT      NOT NULL,
    type           VARCHAR(20) NOT NULL,
    quantity       BIGINT      NOT NULL,
    quantity_after BIGINT      NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_stock_history_product FOREIGN KEY (product_id) REFERENCES product (id),
    CONSTRAINT ck_stock_history_type CHECK (type IN ('INBOUND', 'OUTBOUND')),
    CONSTRAINT ck_stock_history_quantity_positive CHECK (quantity > 0),
    CONSTRAINT ck_stock_history_quantity_after_non_negative CHECK (quantity_after >= 0)
);

CREATE INDEX idx_stock_history_product_id_id ON stock_history (product_id, id DESC);
